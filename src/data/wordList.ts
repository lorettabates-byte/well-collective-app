export const VALID_5: Set<string> = new Set(
  W5.split(/\s+/).map(w => w.trim()).filter(w => w.length === 5)
);

const ALL_WORDS_RAW: string[] = [
  ...WMULTI.trim().split(/\s+/),
  ...WEXTRA.trim().split(/\s+/),
].map(w => w.trim()).filter(Boolean);

// Combined set for all lengths (3–8)
export const VALID_WORDS: Set<string> = new Set([
  ...ALL_WORDS_RAW.filter(w => w.length >= 3 && w.length <= 8),
  ...VALID_5,
]);

export function isValid5Letter(word: string): boolean {
  return VALID_5.has(word.toUpperCase());
}

export function isValidWord(word: string, minLen = 3): boolean {
  const w = word.toUpperCase();
  if (w.length < minLen) return false;
  return VALID_WORDS.has(w);
}

